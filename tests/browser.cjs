// Run with Playwright installed: node tests/browser.cjs. No mic/camera permissions.
const {chromium} = require('playwright');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({headless:true, channel: process.env.ARKUS_BROWSER_CHANNEL || undefined});
  const errors = [];
  const page = await browser.newPage({viewport:{width:1440,height:900}, reducedMotion:'reduce'});
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => {if(message.type()==='error') errors.push(message.text());});
  const base = process.env.ARKUS_TEST_URL || 'http://127.0.0.1:4700';
  const output = process.env.ARKUS_TEST_OUTPUT || 'test-results';
  fs.mkdirSync(output,{recursive:true});
  await page.goto(base+'/?mute=1&focusprobe=1', {waitUntil:'networkidle'});
  await page.waitForFunction(()=>window.arkusProbe !== undefined);
  const probe = await page.title();
  if(!probe.includes('PASS')) throw new Error(probe);
  if(await page.locator('body').getAttribute('data-galaxy')!=='ready') throw new Error('WebGL galaxy failed');
  await page.locator('#probeResults').evaluate(node=>node.remove());
  await page.screenshot({path:path.join(output,'arkus-desktop.png')});
  await page.locator('#question').fill('What are the payment terms?');
  await page.locator('#chatForm').evaluate(form=>form.requestSubmit());
  await page.locator('#sourceTitle').filter({hasText:'Payment terms'}).waitFor();
  await page.locator('.message.assistant').filter({hasText:'fifty percent'}).waitFor();
  await page.locator('#question').fill('Compare payment terms pricing policy cash reserve invoice checklist expense review');
  await page.locator('#chatForm').evaluate(form=>form.requestSubmit());
  await page.locator('#toast').filter({hasText:'sources illuminated'}).waitFor();
  const marker='browserrecall'+Date.now();
  await page.locator('#question').fill('remember that '+marker+' confirms the star is born live');
  await page.locator('#chatForm').evaluate(form=>form.requestSubmit());
  await page.locator('#sourceTitle').filter({hasText:marker}).waitFor();
  await page.locator('#question').fill(marker);
  await page.locator('#chatForm').evaluate(form=>form.requestSubmit());
  await page.locator('.message.assistant').filter({hasText:'confirms the star'}).last().waitFor();
  await page.locator('#settingsToggle').click();
  await page.locator('#focusStart').click();
  await page.locator('#focusBadge').filter({hasText:'FOCUSING'}).waitFor();
  await page.reload({waitUntil:'networkidle'});
  await page.locator('#probeResults').evaluate(node=>node.remove());
  await page.locator('#settingsToggle').click();
  await page.locator('#focusBadge').filter({hasText:'FOCUSING'}).waitFor();
  await page.locator('[data-focus="abort"]').click();
  await page.locator('#focusBadge').filter({hasText:'OFF'}).waitFor();
  await page.locator('#closeSettings').click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(output,'arkus-mobile.png')});
  const overflow = await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  if(overflow) throw new Error('Mobile horizontal overflow');
  await page.locator('#settingsToggle').click();
  await page.screenshot({path:path.join(output,'arkus-mobile-controls.png')});
  if(errors.length) throw new Error(errors.join('\n'));
  console.log(probe+'; live chat, source focus, capture, recall, focus reload, mobile layout PASS; console errors 0');
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
